export const isLessonUnlocked = (lessonId: string, completedIds: string[]): boolean => {
  const lesson = lessons.find((l) => l.id === lessonId);
  if (!lesson) return false;
  if (lesson.order === 1) return true;
  
  const previousLesson = lessons.find((l) => l.moduleId === lesson.moduleId && l.order === lesson.order - 1);
  if (!previousLesson) {
    const previousModule = lessons
      .filter((l) => l.moduleId !== lesson.moduleId)
      .sort((a, b) => b.order - a.order)[0];
    return previousModule ? completedIds.includes(previousModule.id) : false;
  }
  
  return completedIds.includes(previousLesson.id);
};

export const lessonById = (id: string) => lessons.find((lesson) => lesson.id === id);
